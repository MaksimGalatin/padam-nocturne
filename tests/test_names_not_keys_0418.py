# -*- coding: utf-8 -*-
"""Имена рядом со словом «ключ / токен» — не ключи (0.4.18, 13.11.2026).

Перепроверка трекера недоделок на 0.4.17: 11 из 17 срабатываний были именами, а не значениями — имя токена с датой,
имя переменной, PascalCase-название политики, тег модели, файл с русским именем, маски файлов. Здесь — формы этих имён
(значения выдуманы) и контроль: настоящий по виду ключ в той же фразе по-прежнему маскируется.
"""
import pytest

from padam import safety

ИМЕНА = [
    "Новое: токен GitHub aifa-brain-sync-workflow-2026-10 истекает в среду",
    "подключить Vercel-токен aifa-ci-2026-10-17 в окружение",
    "второй ключ подключить как GOOGLE_AI_PRO_KEY_2 в окружение",
    "ключ не нужен: политика LimitBlankPasswordUse включена",
    "ключ OLLAMA_API_KEY задан, модель по умолчанию gemma3:27b-cloud сегодня",
    "оригиналы с ключом лежат в файле ключи_оригиналы_1710.txt рядом",
    "не копировать ключи: client_secret, *.pem/*.p12/*.key/*.jwk, id_rsa",
    "ключи SSH лежат в файлах id_rsa/id_ed25519 в папке .ssh",
]


@pytest.mark.parametrize("фраза", ИМЕНА)
def test_имя_рядом_с_подписью_ключа_не_маскируется(фраза):
    out, kinds = safety.redact(фраза)
    assert out == фраза, (kinds, out)


def test_настоящий_ключ_рядом_с_именем_маскируется():
    ключ = "q7Zp2Lw9Xk4Rt8Vb3Nm6Hc1Jd5Fg0Sa"  # СЕКРЕТ-ПРОВЕРЕН: выдуманный ключ для теста
    out, _ = safety.redact(f"токен aifa-ci-2026-10-17 заменён, новый токен {ключ} — сохрани")
    assert ключ not in out and "aifa-ci-2026-10-17" in out
